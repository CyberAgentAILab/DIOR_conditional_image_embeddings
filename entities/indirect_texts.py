from typing import List, Optional

from pydantic import BaseModel, Field


class InDiReCTTextConfig(BaseModel):
    """Configuration for text descriptions used in InDiReCT."""

    dataset: str = Field(...)
    aspect: str = Field(...)
    template: str = Field(...)
    items: List[str] = Field(...)

    def get_texts(self) -> List[str]:
        """Generate text descriptions from template and items."""
        return [self.template.format(item=item) for item in self.items]


